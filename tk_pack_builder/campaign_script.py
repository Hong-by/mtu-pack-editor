from __future__ import annotations

from collections.abc import Callable
from typing import Any


def build_campaign_start_script(
    spawn_entries: list[dict[str, Any]],
    ceo_entries: list[dict[str, Any]],
    equipment_entries: list[dict[str, Any]],
    *,
    escape: Callable[[str], str],
    string_list: Callable[[list[str]], str],
) -> str | None:
    """Build the small, guarded campaign script shipped in generated packs.

    Keep runtime work deliberately narrow: summon the generated template, move
    it to the local human faction if necessary, grant requested equipment to
    that faction's inventory, and apply explicit character CEO edits.  The
    inventory call exactly follows CA's Three Kingdoms scripts and never equips
    an item on a character.
    """
    if not spawn_entries and not ceo_entries and not equipment_entries:
        return None

    lines = [
        "-- Auto-generated by MTU Pack Editor.",
        "-- Uses only CA's native 3K modify interfaces; equipment is inventory-only.",
        "local hby_spawn_items = {",
    ]
    for entry in spawn_entries:
        lines.append(
            "    { "
            f'template = "{escape(str(entry["template"]))}", '
            f'subtype = "{escape(str(entry["subtype"]))}", '
            f'event = "{escape(str(entry.get("event") or ""))}", '
            f'turn = {int(entry.get("turn") or 0)}, '
            f'save_key = "{escape(str(entry["saveKey"]))}", '
            f'attempt_key = "{escape(str(entry["attemptKey"]))}" '
            "},"
        )
    lines.extend(["}", "", "local hby_ceo_items = {"])
    for entry in ceo_entries:
        lines.append(
            "    { "
            f'template = "{escape(str(entry["template"]))}", '
            f'save_key = "{escape(str(entry["saveKey"]))}", '
            f'title_ceo = "{escape(str(entry.get("titleCeoKey") or ""))}", '
            f'remove_ceos = {string_list(list(entry.get("removeCeos") or []))}, '
            f'add_ceos = {string_list(list(entry.get("addCeos") or []))} '
            "},"
        )
    lines.extend(["}", "", "local hby_equipment_items = {"])
    for entry in equipment_entries:
        lines.append(
            "    { "
            f'template = "{escape(str(entry["template"]))}", '
            f'save_key = "{escape(str(entry["saveKey"]))}", '
            f'grant_key = "{escape(str(entry["grantKey"]))}", '
            f'ceos = {string_list(list(entry.get("grantEquipmentCeos") or []))} '
            "},"
        )
    lines.extend([
        "}",
        "",
        "local function hby_faction_key(value)",
        '    if type(value) == "string" then',
        "        return value",
        "    end",
        "    if value then",
        "        local ok, name = pcall(function() return value:name() end)",
        '        if ok and type(name) == "string" then',
        "            return name",
        "        end",
        "    end",
        '    return ""',
        "end",
        "",
        "local function hby_character(template_key)",
        "    local ok, character = pcall(function()",
        "        return cm:query_model():character_for_template(template_key)",
        "    end)",
        "    if not ok or not character then",
        "        return nil",
        "    end",
        "    local null_ok, is_null = pcall(function() return character:is_null_interface() end)",
        "    if null_ok and is_null then",
        "        return nil",
        "    end",
        "    local dead_ok, is_dead = pcall(function() return character:is_dead() end)",
        "    if dead_ok and is_dead then",
        "        return nil",
        "    end",
        "    return character",
        "end",
        "",
        "local function hby_prepare_character(template_key, faction_key)",
        "    local character = hby_character(template_key)",
        "    if not character then",
        "        return false",
        "    end",
        "    local faction_ok, current_faction = pcall(function() return character:faction():name() end)",
        "    local leader_ok, is_leader = pcall(function() return character:is_faction_leader() end)",
        "    if faction_ok and current_faction ~= faction_key and not (leader_ok and is_leader) then",
        "        local moved = pcall(function()",
        "            cm:modify_character(character):move_to_faction_and_make_recruited(faction_key)",
        "        end)",
        "        if not moved then",
        '            output("MTU Pack Editor: character move failed: " .. tostring(template_key))',
        "            return false",
        "        end",
        "    end",
        "    return true",
        "end",
        "",
        "local function hby_spawn_one(item, faction_key, turn_number)",
        "    if cm:get_saved_value(item.save_key) then",
        "        return true",
        "    end",
        "    if item.event ~= \"campaign_start\" and turn_number < item.turn then",
        "        return false",
        "    end",
        "    if hby_prepare_character(item.template, faction_key) then",
        "        cm:set_saved_value(item.save_key, true)",
        "        return true",
        "    end",
        "    if cm:get_saved_value(item.attempt_key) == turn_number then",
        "        return false",
        "    end",
        "    cm:set_saved_value(item.attempt_key, turn_number)",
        "    local ok = pcall(function()",
        "        cm:modify_faction(faction_key):create_character_from_template(",
        '            "general", item.subtype, item.template, true',
        "        )",
        "    end)",
        "    if not ok then",
        '        output("MTU Pack Editor: character spawn failed: " .. tostring(item.template))',
        "        return false",
        "    end",
        "    if hby_prepare_character(item.template, faction_key) then",
        "        cm:set_saved_value(item.save_key, true)",
        '        output("MTU Pack Editor: character created: " .. tostring(item.template))',
        "        return true",
        "    end",
        "    return false",
        "end",
        "",
        "local function hby_grant_equipment(item, faction_key)",
        "    if cm:get_saved_value(item.save_key) then",
        "        return true",
        "    end",
        "    local all_added = true",
        "    for i = 1, #item.ceos do",
        "        local item_save_key = item.grant_key .. \"_\" .. tostring(i)",
        "        if not cm:get_saved_value(item_save_key) then",
        "            local ceo_key = item.ceos[i]",
        "            local ok = pcall(function()",
        "                cm:modify_faction(faction_key):ceo_management():add_ceo(ceo_key)",
        "            end)",
        "            if ok then",
        "                cm:set_saved_value(item_save_key, true)",
        "            else",
        "                all_added = false",
        '                output("MTU Pack Editor: inventory grant failed: " .. tostring(ceo_key))',
        "            end",
        "        end",
        "    end",
        "    if all_added then",
        "        cm:set_saved_value(item.save_key, true)",
        '        output("MTU Pack Editor: equipment granted to faction inventory: " .. tostring(item.template))',
        "    end",
        "    return all_added",
        "end",
        "",
        "local function hby_apply_ceos(item)",
        "    if cm:get_saved_value(item.save_key) then",
        "        return true",
        "    end",
        "    local character = hby_character(item.template)",
        "    if not character then",
        "        return false",
        "    end",
        "    local ok = pcall(function()",
        "        local manager = cm:modify_character(character):ceo_management()",
        "        for i = 1, #item.remove_ceos do",
        "            manager:remove_ceos(item.remove_ceos[i])",
        "        end",
        '        if item.title_ceo ~= "" then',
        "            manager:add_ceo(item.title_ceo)",
        "        end",
        "        for i = 1, #item.add_ceos do",
        "            manager:add_ceo(item.add_ceos[i])",
        "        end",
        "    end)",
        "    if ok then",
        "        cm:set_saved_value(item.save_key, true)",
        "    else",
        '        output("MTU Pack Editor: character CEO update failed: " .. tostring(item.template))',
        "    end",
        "    return ok",
        "end",
        "",
        "local function hby_pending()",
        "    for i = 1, #hby_spawn_items do",
        "        if not cm:get_saved_value(hby_spawn_items[i].save_key) then return true end",
        "    end",
        "    for i = 1, #hby_equipment_items do",
        "        if not cm:get_saved_value(hby_equipment_items[i].save_key) then return true end",
        "    end",
        "    for i = 1, #hby_ceo_items do",
        "        if not cm:get_saved_value(hby_ceo_items[i].save_key) then return true end",
        "    end",
        "    return false",
        "end",
        "",
        "local function hby_run(faction_key)",
        "    faction_key = hby_faction_key(faction_key)",
        '    if faction_key == "" then',
        "        return",
        "    end",
        "    local turn_number = cm:turn_number() or 0",
        "    for i = 1, #hby_spawn_items do",
        "        hby_spawn_one(hby_spawn_items[i], faction_key, turn_number)",
        "    end",
        "    for i = 1, #hby_equipment_items do",
        "        hby_grant_equipment(hby_equipment_items[i], faction_key)",
        "    end",
        "    for i = 1, #hby_ceo_items do",
        "        hby_apply_ceos(hby_ceo_items[i])",
        "    end",
        "end",
        "",
        "local function hby_register_retry_listener()",
        "    if not core or not core.add_listener then return end",
        "    core:add_listener(",
        '        "hby_mtu_pack_editor_retry",',
        '        "FactionTurnStart",',
        "        function(context)",
        "            local ok, wanted = pcall(function()",
        "                return context:faction():is_human() and hby_pending()",
        "            end)",
        "            return ok and wanted",
        "        end,",
        "        function(context)",
        "            local ok, err = pcall(function() hby_run(context:faction():name()) end)",
        '            if not ok then output("MTU Pack Editor: retry error: " .. tostring(err)) end',
        "        end,",
        "        true",
        "    )",
        "end",
        "",
        "if cm and cm.add_first_tick_callback then",
        "    cm:add_first_tick_callback(function()",
        "        local ok, err = pcall(function()",
        "            local faction_key = hby_faction_key(cm:get_local_faction())",
        "            hby_run(faction_key)",
        "            if hby_pending() then hby_register_retry_listener() end",
        "        end)",
        '        if not ok then output("MTU Pack Editor: first tick error: " .. tostring(err)) end',
        "    end)",
        "end",
        "",
    ])
    return "\n".join(lines)
