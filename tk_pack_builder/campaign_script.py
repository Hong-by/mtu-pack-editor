from __future__ import annotations

from collections.abc import Callable
from typing import Any


def build_campaign_start_script(
    spawn_entries: list[dict[str, Any]],
    ceo_entries: list[dict[str, Any]],
    equipment_entries: list[dict[str, Any]],
    *,
    work_entries: list[dict[str, str]] | None = None,
    escape: Callable[[str], str],
    string_list: Callable[[list[str]], str],
) -> str | None:
    """Build the small, guarded campaign script shipped in generated packs.

    Keep runtime work deliberately narrow: summon the generated template, move
    it to the local human faction if necessary, grant requested equipment to
    that faction's inventory, and apply explicit character CEO edits.  The
    inventory call exactly follows CA's Three Kingdoms scripts and never equips
    an item on a character.
    """
    if not spawn_entries and not ceo_entries and not equipment_entries and not work_entries:
        return None

    lines = [
        "-- Auto-generated by MTU Pack Editor.",
        "-- Uses only CA's native 3K modify interfaces; equipment is inventory-only.",
        "local hby_spawn_items = {",
    ]
    for entry in spawn_entries:
        lines.append(
            "    { "
            f'template = "{escape(str(entry["template"]))}", '
            f'subtype = "{escape(str(entry["subtype"]))}", '
            f'event = "{escape(str(entry.get("event") or ""))}", '
            f'turn = {int(entry.get("turn") or 0)}, '
            f'save_key = "{escape(str(entry["saveKey"]))}", '
            f'attempt_key = "{escape(str(entry["attemptKey"]))}" '
            "},"
        )
    lines.extend(["}", "", "local hby_ceo_items = {"])
    for entry in ceo_entries:
        lines.append(
            "    { "
            f'template = "{escape(str(entry["template"]))}", '
            f'save_key = "{escape(str(entry["saveKey"]))}", '
            f'title_ceo = "{escape(str(entry.get("titleCeoKey") or ""))}", '
            f'remove_ceos = {string_list(list(entry.get("removeCeos") or []))}, '
            f'add_ceos = {string_list(list(entry.get("addCeos") or []))} '
            "},"
        )
    existing_equipment_entries = [
        entry for entry in equipment_entries if entry.get("existingOnly")
    ]
    regular_equipment_entries = [
        entry for entry in equipment_entries if not entry.get("existingOnly")
    ]
    lines.extend(["}", "", "local hby_existing_equipment_items = {"])
    for entry in existing_equipment_entries:
        lines.append(
            "    { "
            f'template = "{escape(str(entry["template"]))}", '
            f'save_key = "{escape(str(entry["saveKey"]))}", '
            f'grant_key = "{escape(str(entry["grantKey"]))}", '
            f'ceos = {string_list(list(entry.get("grantEquipmentCeos") or []))}, '
            f'best_effort = {"true" if entry.get("bestEffort") else "false"} '
            "},"
        )
    lines.extend(["}", "", "local hby_equipment_items = {"])
    for entry in regular_equipment_entries:
        lines.append(
            "    { "
            f'template = "{escape(str(entry["template"]))}", '
            f'save_key = "{escape(str(entry["saveKey"]))}", '
            f'grant_key = "{escape(str(entry["grantKey"]))}", '
            f'ceos = {string_list(list(entry.get("grantEquipmentCeos") or []))}, '
            f'best_effort = {"true" if entry.get("bestEffort") else "false"} '
            "},"
        )
    lines.extend([
        "}",
        "",
        "local function hby_faction_key(value)",
        '    if type(value) == "string" then',
        "        return value",
        "    end",
        "    if value then",
        "        local ok, name = pcall(function() return value:name() end)",
        '        if ok and type(name) == "string" then',
        "            return name",
        "        end",
        "    end",
        '    return ""',
        "end",
        "",
        "local function hby_character(template_key)",
        "    local ok, character = pcall(function()",
        "        return cm:query_model():character_for_template(template_key)",
        "    end)",
        "    if not ok or not character then",
        "        return nil",
        "    end",
        "    local null_ok, is_null = pcall(function() return character:is_null_interface() end)",
        "    if null_ok and is_null then",
        "        return nil",
        "    end",
        "    local dead_ok, is_dead = pcall(function() return character:is_dead() end)",
        "    if dead_ok and is_dead then",
        "        return nil",
        "    end",
        "    return character",
        "end",
        "",
        "local function hby_prepare_character(template_key, faction_key)",
        "    local character = hby_character(template_key)",
        "    if not character then",
        "        return false",
        "    end",
        "    local faction_ok, current_faction = pcall(function() return character:faction():name() end)",
        "    local leader_ok, is_leader = pcall(function() return character:is_faction_leader() end)",
        "    if faction_ok and current_faction ~= faction_key and not (leader_ok and is_leader) then",
        "        local moved = pcall(function()",
        "            cm:modify_character(character):move_to_faction_and_make_recruited(faction_key)",
        "        end)",
        "        if not moved then",
        '            output("MTU Pack Editor: character move failed: " .. tostring(template_key))',
        "            return false",
        "        end",
        "    end",
        "    return true",
        "end",
        "",
        "local function hby_spawn_one(item, faction_key, turn_number)",
        "    if cm:get_saved_value(item.save_key) then",
        "        return true",
        "    end",
        "    if item.event ~= \"campaign_start\" and turn_number < item.turn then",
        "        return false",
        "    end",
        "    if hby_prepare_character(item.template, faction_key) then",
        "        cm:set_saved_value(item.save_key, true)",
        "        return true",
        "    end",
        "    if cm:get_saved_value(item.attempt_key) == turn_number then",
        "        return false",
        "    end",
        "    cm:set_saved_value(item.attempt_key, turn_number)",
        "    local ok = pcall(function()",
        "        cm:modify_faction(faction_key):create_character_from_template(",
        # Match CA's historical-character spawn helper.  The final false keeps
        # the template's fixed spawn-age row instead of generating a random
        # adult character age.
        '            "general", item.subtype, item.template, false',
        "        )",
        "    end)",
        "    if not ok then",
        '        output("MTU Pack Editor: character spawn failed: " .. tostring(item.template))',
        "        return false",
        "    end",
        "    if hby_prepare_character(item.template, faction_key) then",
        "        cm:set_saved_value(item.save_key, true)",
        '        output("MTU Pack Editor: character created: " .. tostring(item.template))',
        "        return true",
        "    end",
        "    return false",
        "end",
        "",
        "local function hby_add_ceo(ceo_manager, ceo_key)",
        "    local ok, result = pcall(function() return ceo_manager:add_ceo(ceo_key) end)",
        "    return ok and result ~= false",
        "end",
        "",
        "local function hby_remove_ceo(ceo_manager, ceo_key)",
        # Three Kingdoms exposes the plural remove_ceos API. MTU's own
        # campaign scripts use this exact method. Calling the singular form
        # fails inside pcall and used to leave the retry listener active on
        # every subsequent human FactionTurnStart.
        "    local ok, result = pcall(function() return ceo_manager:remove_ceos(ceo_key) end)",
        "    return ok and result ~= false",
        "end",
        "",
        "local function hby_character_ceo_for_category(character, category_key)",
        "    local manager_ok, manager = pcall(function()",
        "        return character:ceo_management()",
        "    end)",
        "    if not manager_ok or not manager then",
        "        return nil",
        "    end",
        "    local list_ok, ceos = pcall(function()",
        "        return manager:all_ceos_for_category(category_key)",
        "    end)",
        "    if not list_ok or not ceos then",
        "        return nil",
        "    end",
        "    local count_ok, count = pcall(function() return ceos:num_items() end)",
        "    if not count_ok or not count then",
        "        return nil",
        "    end",
        "    for index = 0, count - 1 do",
        "        local item_ok, item = pcall(function() return ceos:item_at(index) end)",
        "        if item_ok and item then",
        "            local key_ok, key = pcall(function() return item:ceo_data_key() end)",
        '            if key_ok and type(key) == "string" and key ~= "" then',
        "                return key",
        "            end",
        "        end",
        "    end",
        "    return nil",
        "end",
        "",
        "local function hby_set_character_title(character, manager, title_ceo)",
        '    if title_ceo == "" then',
        "        return true",
        "    end",
        '    local category_key = "3k_main_ceo_category_career"',
        "    local current_title = hby_character_ceo_for_category(character, category_key)",
        "    if current_title == title_ceo then",
        "        return true",
        "    end",
        '    if current_title and current_title ~= "" then',
        "        hby_remove_ceo(manager, current_title)",
        "    end",
        "    if not hby_add_ceo(manager, title_ceo) then",
        "        return false",
        "    end",
        "    return hby_character_ceo_for_category(character, category_key) == title_ceo",
        "end",
        "",
        "local function hby_add_ancillary_to_faction(faction_key, ancillary_key)",
        "    local modify_ok, faction = pcall(function()",
        "        return cm:modify_faction(faction_key)",
        "    end)",
        "    if not modify_ok or not faction then",
        "        return false",
        "    end",
        "    local manager_ok, manager = pcall(function()",
        "        return faction:ceo_management()",
        "    end)",
        "    if not manager_ok or not manager then",
        "        return false",
        "    end",
        "    local ok, result = pcall(function()",
        # Match The Gathering Sandbox and 190E's own inventory helper.  Adding
        # the CEO to the faction manager creates an inventory item without
        # equipping or mutating any character slot.
        "        return manager:add_ceo(ancillary_key)",
        "    end)",
        "    return ok and result ~= false",
        "end",
        "",
        "local function hby_grant_equipment(item, faction_key)",
        "    if cm:get_saved_value(item.save_key) then",
        "        return true",
        "    end",
        "    local all_added = true",
        "    for i = 1, #item.ceos do",
        "        local item_save_key = item.grant_key .. \"_\" .. tostring(i)",
        "        if not cm:get_saved_value(item_save_key) then",
        "            local ceo_key = item.ceos[i]",
        "            local added = hby_add_ancillary_to_faction(faction_key, ceo_key)",
        "            if added then",
        "                cm:set_saved_value(item_save_key, true)",
        "            else",
        "                all_added = false",
        '                output("MTU Pack Editor: inventory grant failed: " .. tostring(ceo_key))',
        "            end",
        "        end",
        "    end",
        "    if all_added then",
        "        cm:set_saved_value(item.save_key, true)",
        '        output("MTU Pack Editor: equipment granted to faction inventory: " .. tostring(item.template))',
        "    end",
        "    return all_added",
        "end",
        "",
        "local function hby_migrate_existing_equipment(item, faction_key)",
        "    if cm:get_saved_value(item.save_key) then",
        "        return true",
        "    end",
        "    if not hby_character(item.template) then",
        "        return false",
        "    end",
        "    return hby_grant_equipment(item, faction_key)",
        "end",
        "",
        "local function hby_apply_ceos(item)",
        "    if cm:get_saved_value(item.save_key) then",
        "        return true",
        "    end",
        "    local character = hby_character(item.template)",
        "    if not character then",
        "        return false",
        "    end",
        "    local manager_ok, manager = pcall(function()",
        "        return cm:modify_character(character):ceo_management()",
        "    end)",
        "    if not manager_ok or not manager then",
        '        output("MTU Pack Editor: character CEO manager unavailable: " .. tostring(item.template))',
        "        return false",
        "    end",
        "    local all_applied = true",
        "    for i = 1, #item.remove_ceos do",
        # Removal is deliberately best-effort. The generated character may
        # already have a generic career CEO instead of its source template's
        # title; hby_set_character_title removes the actual current career CEO.
        "        hby_remove_ceo(manager, item.remove_ceos[i])",
        "    end",
        "    if not hby_set_character_title(character, manager, item.title_ceo) then",
        "        all_applied = false",
        "    end",
        "    for i = 1, #item.add_ceos do",
        "        if not hby_add_ceo(manager, item.add_ceos[i]) then",
        "            all_applied = false",
        "        end",
        "    end",
        "    if not all_applied then",
        '        output("MTU Pack Editor: character CEO update failed: " .. tostring(item.template))',
        "        return false",
        "    end",
        "    cm:set_saved_value(item.save_key, true)",
        '    output("MTU Pack Editor: character title and traits applied: " .. tostring(item.template))',
        "    return true",
        "end",
        "",
        "local function hby_pending()",
        "    for i = 1, #hby_existing_equipment_items do",
        "        if not cm:get_saved_value(hby_existing_equipment_items[i].save_key) then return true end",
        "    end",
        "    for i = 1, #hby_spawn_items do",
        "        if not cm:get_saved_value(hby_spawn_items[i].save_key) then return true end",
        "    end",
        "    for i = 1, #hby_equipment_items do",
        "        if not cm:get_saved_value(hby_equipment_items[i].save_key) then return true end",
        "    end",
        "    for i = 1, #hby_ceo_items do",
        "        if not cm:get_saved_value(hby_ceo_items[i].save_key) then return true end",
        "    end",
        "    return false",
        "end",
        "",
        "local function hby_run(faction_key)",
        "    faction_key = hby_faction_key(faction_key)",
        '    if faction_key == "" then',
        "        return",
        "    end",
        "    local turn_number = cm:turn_number() or 0",
        "    for i = 1, #hby_existing_equipment_items do",
        "        hby_migrate_existing_equipment(hby_existing_equipment_items[i], faction_key)",
        "    end",
        "    for i = 1, #hby_spawn_items do",
        "        hby_spawn_one(hby_spawn_items[i], faction_key, turn_number)",
        "    end",
        "    for i = 1, #hby_equipment_items do",
        "        hby_grant_equipment(hby_equipment_items[i], faction_key)",
        "    end",
        "    for i = 1, #hby_ceo_items do",
        "        hby_apply_ceos(hby_ceo_items[i])",
        "    end",
        "end",
        "",
        "local function hby_register_retry_listener()",
        "    if not core or not core.add_listener then return end",
        "    core:add_listener(",
        '        "hby_mtu_pack_editor_retry",',
        '        "FactionTurnStart",',
        "        function(context)",
        "            local ok, wanted = pcall(function()",
        "                return context:faction():is_human() and hby_pending()",
        "            end)",
        "            return ok and wanted",
        "        end,",
        "        function(context)",
        "            local ok, err = pcall(function() hby_run(context:faction():name()) end)",
        '            if not ok then output("MTU Pack Editor: retry error: " .. tostring(err)) end',
        "        end,",
        "        true",
        "    )",
        "end",
        "",
        "if cm and cm.add_first_tick_callback then",
        "    cm:add_first_tick_callback(function()",
        "        local ok, err = pcall(function()",
        "            local faction_key = hby_faction_key(cm:get_local_faction())",
        "            hby_run(faction_key)",
        "            if hby_pending() then hby_register_retry_listener() end",
        "        end)",
        '        if not ok then output("MTU Pack Editor: first tick error: " .. tostring(err)) end',
        "    end)",
        "end",
        "",
    ])
    return _with_diagnostics(lines, work_entries or [
        {"template": str(entry["template"]), "kind": str(entry.get("workKind") or
         ("new_character" if entry in spawn_entries else "existing_character"))}
        for entry in [*spawn_entries, *ceo_entries, *equipment_entries]
    ], escape)


def _with_diagnostics(lines: list[str], work_entries: list[dict[str, str]], escape: Callable[[str], str]) -> str:
    """Instrument the existing calls without changing their returns or ordering."""
    prelude = r'''-- HBY_DIAG v1: append/flush/close each record; logging failure never stops gameplay.
local hby_diag_seq = 0
local hby_diag_template = "-"
local hby_diag_kind = "runtime"
local hby_diag_detail = ""
local hby_diag_kinds = {}
local function hby_diag(stage, status, detail)
    pcall(function()
        hby_diag_seq = hby_diag_seq + 1
        local line = "[HBY_DIAG v1] seq=" .. tostring(hby_diag_seq)
            .. " kind=" .. hby_diag_kind .. " template=" .. hby_diag_template
            .. " stage=" .. stage .. " status=" .. status
            .. " detail=" .. tostring(detail or hby_diag_detail):gsub("[\r\n]", " ")
        if io and io.open then
            pcall(function()
                local file = io.open("hby_mtu_pack_editor_diagnostic.log", "a")
                if file then file:write(line .. "\n"); file:flush(); file:close() end
            end)
        end
        if type(output) == "function" then pcall(output, line) end
    end)
end
local function hby_diag_context(template)
    hby_diag_template = tostring(template or "-")
    hby_diag_kind = hby_diag_kinds[hby_diag_template] or "runtime"
    hby_diag_detail = ""
end
hby_diag("script_load", "begin", "diagnostics=1")
'''
    manifest = []
    for entry in work_entries:
        template, kind = escape(entry["template"]), escape(entry["kind"])
        manifest.extend([
            f'hby_diag_kinds["{template}"] = "{kind}"',
            f'hby_diag_context("{template}")',
            'hby_diag("work_manifest", "info", "DB changes load before first_tick; runtime entries may be absent")',
        ])
    manifest.append('hby_diag_context(nil)')
    instrumented = []
    function = "registration"
    call_index = 0
    pending: list[tuple[str, str, str]] = []
    for line in lines:
        stripped = line.strip()
        if stripped == "if cm and cm.add_first_tick_callback then":
            function, call_index = "first_tick", 0
        if stripped.startswith("local function "):
            function = stripped.split("local function ", 1)[1].split("(", 1)[0]
            call_index = 0
        if "pcall(function()" in line:
            call_index += 1
            indent = line[:len(line) - len(line.lstrip())]
            label = f"{function}.call_{call_index}"
            result = "nil"
            if stripped.startswith("local ") and " = pcall" in stripped:
                result = stripped[6:].split(" = pcall", 1)[0].split(",")[0].strip()
            instrumented.append(f'{indent}hby_diag("{label}", "before")')
            if stripped.endswith("end)"):
                instrumented.extend([line, f'{indent}hby_diag("{label}", "after", "pcall_ok=" .. tostring({result}))'])
                continue
            pending.append((indent, label, result))
        instrumented.append(line)
        if pending and stripped == "end)" and line.startswith(pending[-1][0]) and len(line)-len(line.lstrip()) == len(pending[-1][0]):
            indent, label, result = pending.pop()
            instrumented.append(f'{indent}hby_diag("{label}", "after", "pcall_ok=" .. tostring({result}))')
        if stripped.startswith("local function "):
            if stripped.endswith("(item, faction_key, turn_number)") or stripped.endswith("(item, faction_key)") or stripped.endswith("(item)"):
                instrumented.append('    hby_diag_context(item.template)')
            if "(ceo_manager, ceo_key)" in stripped:
                instrumented.append('    hby_diag_detail = "ceo=" .. tostring(ceo_key)')
            if "(faction_key, ancillary_key)" in stripped:
                instrumented.append('    hby_diag_detail = "equipment=" .. tostring(ancillary_key)')
            if "(character, category_key)" in stripped:
                instrumented.append('    hby_diag_detail = "category=" .. tostring(category_key)')
            if "(character, manager, title_ceo)" in stripped:
                instrumented.append('    hby_diag_detail = "title=" .. tostring(title_ceo)')
            instrumented.append(f'    hby_diag("{function}", "enter")')
        if stripped == "cm:add_first_tick_callback(function()":
            instrumented.extend(['        hby_diag_context(nil)', '        hby_diag("first_tick", "enter")'])
        if stripped.startswith("hby_") and "[i]" in stripped and stripped.endswith(")"):
            instrumented.append('        hby_diag("work_step", "returned")')
    if pending:
        raise ValueError("Unclosed diagnostic call instrumentation")
    return prelude + "\n".join(manifest + instrumented + ['hby_diag_context(nil)', 'hby_diag("script_load", "complete")', ''])
